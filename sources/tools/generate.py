"""Utilise le convertisseur existant en lecture seule; conserve sa provenance."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONVERTER = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT.parents[1] / "transpiler"
if not (CONVERTER / "py2x/__init__.py").is_file():
    raise SystemExit("Indiquez le dossier du convertisseur : python tools/generate.py CHEMIN/transpiler")
sys.path.insert(0, str(CONVERTER))
from py2x import transpile

source = ROOT / "python/mindmap_core.py"
generated = "// Generated by py2x. DO NOT EDIT.\n" + transpile(source.read_text(encoding="utf-8"), "cpp", strict=True)
(ROOT / "generated/mindmap_core.cpp").write_text(generated, encoding="utf-8", newline="\n")
provenance = {
    "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "generated_sha256": hashlib.sha256((ROOT / "generated/mindmap_core.cpp").read_bytes()).hexdigest(),
    "converter_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((CONVERTER / "py2x").glob("*.py"))},
    "flags": {"target": "cpp", "strict": True},
}
(ROOT / "generated/provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8")
print("Core converted; converter unchanged (hashes recorded)")
